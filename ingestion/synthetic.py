"""Generate a SYNTHETIC EDGAR-shaped fixture for tests and offline runs.

Why synthetic: part of EDGAR (IEA-EDGAR CO2) is CC BY-NC-ND 4.0, so this repo does not
redistribute real EDGAR rows. This file copies EDGAR's *structure* exactly (sheet names,
the 195-column header, the 'Units' row), so the real loader reads it unchanged. Every
emission value is invented by a seeded random generator. Nothing here is a real estimate.

What it includes on purpose, so later stages can test their handling:
- the 25 crosswalk urban-centre IDs, with EDGAR's spellings for their names
  (UC IDs and names come from the GHS Urban Centre Database, CC BY 4.0);
- mis-encoded names exactly as EDGAR has them ('SÃ£o Paulo', country 'MÃ©xico');
- a duplicate (name, country) pair: a second 'Lagos, Nigeria' with a fake ID that is not
  in the crosswalk, so joining by name instead of ID would visibly double-count Lagos;
- an urban centre that is not in the crosswalk at all, which modelling must drop;
- a sector that is zero in every year, as happens in the real data.

Two more files re-publish the same release, the way a real source silently fixes a file
under the same name. Loaded in order they are three dataset versions of EDGAR v2024, so the
revisions models see every kind of revision for a crosswalk city:

  original -> revised    the REVISIONS cells change ('changed'), and Dakar's row is
                         missing ('removed': a source dropping an urban centre)
  revised  -> restored   Dakar's row is back, values as in the original ('added')

The last one loaded (restored) is current and covers every crosswalk city, so the models
built on the current version are unaffected. Every other cell is the same in all three.

Regenerate both with:  python -m ingestion make-synthetic
"""

