def header() -> list[str]:
    """The exact EDGAR v2024 column order: pollutant, then sector, then year."""
    return ["ID_UC_G0", "UC_name", "UC_country"] + [
        f"EMI_{p}_{s}_{y}" for p in POLLUTANTS for s in SECTORS for y in YEARS
    ]


def _row(rng: random.Random, uc_id: int, name: str, country: str) -> list:
    scale = rng.uniform(2e5, 3e6)  # invented size of the urban centre's CO2 per sector
    # One CO2 value per (sector, year); every pollutant is derived from that same value,
    # so relationships between columns hold (e.g. total GHG in CO2e is never below CO2).
    co2 = {
        (s, y): 0.0 if (uc_id, s) == ZERO_SECTOR else scale * (1 + 0.06 * i) * rng.uniform(0.8, 1.2)
        for s in SECTORS
        for i, y in enumerate(YEARS)
    }
    values = []
    for pollutant in POLLUTANTS:
        for sector in SECTORS:
            for year in YEARS:
                factor = {"CO2": 1.0, "GWP_100_AR5_GHG": rng.uniform(1.05, 1.6),
                          "NOx": rng.uniform(1e-3, 4e-3), "PM2.5": rng.uniform(1e-4, 8e-4)}[pollutant]
                values.append(round(co2[sector, year] * factor, 6))
    return [uc_id, name, country, *values]


def _apply_revisions(row: list) -> list:
    """Scale the REVISIONS cells of one data row (the row's first cell is its ID)."""
    columns = header()
    row = list(row)
    for uc_id, sector, year, pollutants, factor in REVISIONS:
        if row[0] != uc_id:
            continue
        for pollutant in pollutants:
            i = columns.index(f"EMI_{pollutant}_{sector}_{year}")
            row[i] = round(row[i] * factor, 6)
    return row


def write_synthetic_edgar(path: Path, revised: bool = False) -> int:
    """Write the synthetic fixture, or with revised=True its corrected re-publication."""
    rng = random.Random(SEED)  # same draws either way: the revised file differs only in REVISIONS
    generated_at = REVISED_GENERATED_AT if revised else GENERATED_AT
    wb = Workbook()
    wb.properties.created = wb.properties.modified = generated_at.replace(tzinfo=None)

    notice = wb.active
    notice.title = "citations and references"
    lines = [
        "SYNTHETIC DATA - NOT EDGAR",
        "This workbook was generated by ingestion/synthetic.py for software tests.",
        "It mirrors the structure of EDGAR 'Global emissions in urban areas' v2024.",
        "Every emission value is invented. Do not use it for any analysis.",
        "Real data: https://edgar.jrc.ec.europa.eu/dataset_ucdb",
    ]
    if revised:
        lines.append("REVISED: same release with the cells in synthetic.REVISIONS corrected.")
    for line in lines:
        notice.append([line])

    variables = wb.create_sheet(config.EDGAR_VARIABLES_SHEET)
    for row in (
        ("Information", None), (None, None),
        ("Temporal coverage", ", ".join(map(str, YEARS))),
        ("Units", "ton/year"),
        ("Sectors", "Energy, Industry, Residential, Transport, Agriculture, Waste"),
        ("Pollutants", "CO2, GHG, PM2.5, NOx"),
        ("Name of emission variables", "EMI_pollutant_sector_year"),
    ):
        variables.append(row)

    data = wb.create_sheet(config.EDGAR_DATA_SHEET)
    data.append(header())
    rows = CROSSWALK_URBAN_CENTRES + EXTRA_URBAN_CENTRES
    for uc_id, name, country in rows:
        row = _row(rng, uc_id, name, country)
        data.append(_apply_revisions(row) if revised else row)

    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    _fix_zip_timestamps(path, generated_at)
    return len(rows)


def _fix_zip_timestamps(path: Path, generated_at: datetime = GENERATED_AT) -> None:
    """Make the file byte-for-byte reproducible.

    An .xlsx is a zip archive, and openpyxl stamps each entry with the current time, so
    identical content would get a new SHA-256 (= a new dataset version) on every run.
    openpyxl also overwrites the 'modified' document property with "now" on save, so
    that is pinned too. Afterwards the hash depends on content only.
    """
    with zipfile.ZipFile(path) as src:
        entries = [(info.filename, src.read(info)) for info in src.infolist()]
    fixed = generated_at.strftime("%Y-%m-%dT%H:%M:%SZ").encode()
    entries = [
        (name, re.sub(rb"(<dcterms:modified[^>]*>)[^<]*", rb"\g<1>" + fixed, data)
         if name == "docProps/core.xml" else data)
        for name, data in entries
    ]
    with zipfile.ZipFile(path, "w") as dest:
        for name, data in entries:
            info = zipfile.ZipInfo(name, date_time=generated_at.timetuple()[:6])
            info.compress_type = zipfile.ZIP_DEFLATED
            dest.writestr(info, data)


def manifest_entry(rel_path: str, rows: int, revised: bool = False) -> dict:
    return {
        "source_name": config.EDGAR_SOURCE_NAME, "source_key": config.EDGAR_SOURCE_KEY,
        "origin": "synthetic", "path": rel_path, "rows": rows,
        "source_url": SOURCE_URL, "license": REVISED_LICENSE if revised else LICENSE,
        "upstream_sha256": None,
        "generated_at": (REVISED_GENERATED_AT if revised else GENERATED_AT).isoformat(),
    }
